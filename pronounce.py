_SENTENCE = re.compile(r"[^.!?؟\n]+[.!?؟\n]*")


def is_colloquial(sentence):
    """الجملة عامية لو فيها كلمة من كلمات العامية المشهورة."""
    for w in _WORD.findall(sentence):
        bare = strip_harakat(w)
        if bare in DIALECT_MARKERS:
            return True
        for pre in ("و", "ف", "ب", "ه"):
            if bare.startswith(pre) and bare[1:] in DIALECT_MARKERS and len(bare) > 3:
                return True
    return False


def apply(text, lexicon=None, dialect="auto"):
    """يطبّق قاموس المستخدم والنطق المصري، من غير ما يلمس التاجات [..].

    dialect: "auto" (كل جملة على حسبها، فصحى أو عامية)، "egyptian" (كله عامية)، "fusha" (من غير تحويل).
    """
    lexicon = lexicon or {}
    if dialect is True:
        dialect = "egyptian"
    elif dialect is False:
        dialect = "fusha"

    def fixer(egyptian):
        def fix_word(m):
            word = m.group(0)
            hit = _lookup(word, lexicon) if lexicon else None
            if hit is not None:
                return hit
            if egyptian and not HARAKAT.search(word):
                hit = _lookup(word, EGYPTIAN)
                if hit is not None:
                    return hit
            return word
        return fix_word

    def fix_chunk(chunk):
        if dialect == "auto":
            return "".join(_WORD.sub(fixer(is_colloquial(part)), part) for part in _split_keep(chunk))
        return _WORD.sub(fixer(dialect == "egyptian"), chunk)

    text = clean(text)
    pieces, last = [], 0
    for tm in _TAG.finditer(text):
        pieces.append(fix_chunk(text[last:tm.start()]))
        pieces.append(tm.group(0))
        last = tm.end()
    pieces.append(fix_chunk(text[last:]))
    return "".join(pieces)


def _split_keep(chunk):
    """يقسّم لجمل من غير ما يضيّع أي حرف (المسافات في الأول مثلاً)."""
    parts, pos = [], 0
    for m in _SENTENCE.finditer(chunk):
        if m.start() > pos:
            parts.append(chunk[pos:m.start()])
        parts.append(m.group(0))
        pos = m.end()
    if pos < len(chunk):
        parts.append(chunk[pos:])
    return parts
