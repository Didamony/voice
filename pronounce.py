def clean(text):
    """يرجّع الحروف المنسوخة بشكل غريب لحروف عادية ويشيل التطويل."""
    text = _PRESENTATION.sub(lambda m: unicodedata.normalize("NFKC", m.group(0)), text)
    return text.replace("ـ", "")


def strip_harakat(word):
    return HARAKAT.sub("", word)


def sanitize_lexicon(raw, limit=300):
    """قاموس المستخدم: {الكلمة: إزاي تتنطق}. بيتنضف ويتحدد حجمه."""
    out = {}
    if not isinstance(raw, dict):
        return out
    for k, v in list(raw.items())[:limit]:
        if not isinstance(k, str) or not isinstance(v, str):
            continue
        k, v = strip_harakat(clean(k)).strip(), clean(v).strip()
        if 0 < len(k) <= 40 and 0 < len(v) <= 60 and _WORD.fullmatch(k):
            out[k] = v
    return out


def _lookup(word, table):
    """يدوّر على الكلمة في القاموس، ولو ملقاهاش يجرب يشيل أداة زي (و، ب، ال)."""
    bare = strip_harakat(word)
    if bare in table:
        return table[bare]
    for pre in PREFIXES:
        if bare.startswith(pre) and len(bare) - len(pre) >= 3 and bare[len(pre):] in table:
            return pre + table[bare[len(pre):]]
    return None


